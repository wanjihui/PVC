/*********************************************************************************************************************
* 文件名称          isr.c
* 适用平台          RT1064DVL6A
* 描述              中断服务函数
*
* 分频设计（与 summer-smartcar 的分层思想一致）：
*       PIT_CH0  5ms   200Hz   编码器采样 + 四轮速度环 + IMU 姿态采样
*       PIT_CH1  10ms  100Hz   按键扫描
*       视觉与决策在主循环（跟摄像头帧率走，约 50Hz）
*
* 注意：ISR 里只做确定性的短工作（读编码器、PID、下发 PWM），
*       绝不做视觉、打印、屏幕写入，否则会拖慢内环。
*********************************************************************************************************************/

#include "zf_common_headfile.h"
#include "zf_common_debug.h"
#include "isr.h"

#include "config.h"
#include "encoder.h"
#include "imu.h"
#include "pid.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     200Hz 内环处理：编码器采样 + IMU + 四轮速度环
// 备注信息     只做确定性短工作，禁止视觉/打印/写屏
//-------------------------------------------------------------------------------------------------------------------
void pit_handler_200hz(void)
{
#if ENCODER_ENABLE
    encoder_pit_callback();                                                 // 编码器到货后恢复硬件采样
#endif
    imu_update();                                                           // 陀螺仪采样（滤波器状态 200Hz 更新）
    Speed_PID_Crtl();                                                       // 四轮速度环 → PWM
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     100Hz 处理：按键扫描
// 备注信息     只扫描状态；按键动作由主循环 buttons_poll() 处理（无屏，按键仅用于发车/停车）
//-------------------------------------------------------------------------------------------------------------------
void pit_handler_100hz(void)
{
    key_scanner();
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     PIT 周期中断服务函数
// 备注信息     CH0 与 CH1 共用一个中断向量，靠 pit_flag_get 区分
//-------------------------------------------------------------------------------------------------------------------
void PIT_IRQHandler(void)
{
    if (pit_flag_get(PIT_CH0))
    {
        pit_handler_200hz();
        pit_flag_clear(PIT_CH0);
    }

    if (pit_flag_get(PIT_CH1))
    {
        pit_handler_100hz();
        pit_flag_clear(PIT_CH1);
    }

    if (pit_flag_get(PIT_CH2))
    {
        pit_flag_clear(PIT_CH2);
    }

    if (pit_flag_get(PIT_CH3))
    {
        pit_flag_clear(PIT_CH3);
    }

    __DSB();
}

//-------------------------------------------------------------------------------------------------------------------
// 摄像头 CSI 中断：SDK 内部会回调 mt9v03x 的场中断处理，最终置位 mt9v03x_finish_flag
//-------------------------------------------------------------------------------------------------------------------
void CSI_IRQHandler(void)
{
    CSI_DriverIRQHandler();
    __DSB();                                                                // 数据同步隔离
}

//-------------------------------------------------------------------------------------------------------------------
// 调试串口（LPUART1，B12/B13）
//-------------------------------------------------------------------------------------------------------------------
void LPUART1_IRQHandler(void)
{
    if (kLPUART_RxDataRegFullFlag & LPUART_GetStatusFlags(LPUART1))
    {
    #if DEBUG_UART_USE_INTERRUPT                                            // 如果开启 debug 串口中断
        debug_interrupr_handler();                                          // 数据进 debug 环形缓冲区
    #endif
    }

    LPUART_ClearStatusFlags(LPUART1, kLPUART_RxOverrunFlag);                // 不允许删除
}

//-------------------------------------------------------------------------------------------------------------------
// 遥测串口（LPUART6，B2/B3）：本工程只发不收，仅清标志
//-------------------------------------------------------------------------------------------------------------------
void LPUART6_IRQHandler(void)
{
    if (kLPUART_RxDataRegFullFlag & LPUART_GetStatusFlags(LPUART6))
    {
        /* 预留：如果以后要接收上位机指令，在这里解析 */
    }

    LPUART_ClearStatusFlags(LPUART6, kLPUART_RxOverrunFlag);                // 不允许删除
}
